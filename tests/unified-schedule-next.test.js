const assert=require('node:assert/strict');
const {resolve,afterCompleted}=require('../api/_unified-live-schedule');
const at=(h,m=0)=>new Date(Date.UTC(2026,9,16,h-4,m));
assert.equal(resolve(at(13)).direction,'usa');
assert.equal(resolve(at(16)).displayDirection,'dubai');
assert.equal(resolve(at(17)).direction,'dubai');
assert.equal(resolve(at(20)).displayDirection,'transfer');
assert.equal(resolve(at(21)).direction,'transfer');
assert.equal(resolve(at(0)).displayDirection,'usa');
assert.equal(afterCompleted('usa',at(14,30)).displayDirection,'dubai');
assert.equal(afterCompleted('usa',at(14,30)).secondsRemaining,9000);
assert.equal(afterCompleted('dubai',at(18,9)).displayDirection,'transfer');
assert.equal(afterCompleted('transfer',at(22)).displayDirection,'usa');
assert.throws(()=>afterCompleted('other',at(12)));
console.log('unified schedule checks passed');
